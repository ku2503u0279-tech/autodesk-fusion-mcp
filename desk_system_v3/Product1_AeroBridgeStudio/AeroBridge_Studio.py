def _loop(comp, pts, plane, offset=0.0):
    """Add a closed loop of straight sketch lines on a construction plane.

    `pts` are (depth, height) in millimetres. The section is a dense sampling of
    tangent-continuous curves, so chords between the samples are smooth at any
    real scale. Returns the sketch.
    """
    sk = comp.sketches.add(plane)
    lines = sk.sketchCurves.sketchLines
    vecs = []
    for (a, b) in pts:
        if plane is comp.yZConstructionPlane:
            vecs.append(adsk.core.Point3D.create(offset * MM, b * MM, a * MM))
        else:
            vecs.append(adsk.core.Point3D.create(a * MM, b * MM, 0))
    prev = vecs[0]
    for q in vecs[1:]:
        lines.addByTwoPoints(prev, q)
        prev = q
    lines.addByTwoPoints(prev, vecs[0])
    return sk


def _extrude(comp, sk, depth_mm, name, cut=False, symmetric=False):
    """Extrude the sketch's first profile and return the body (or None)."""
    if sk.profiles.count < 1:
        return None
    prof = sk.profiles.item(0)
    ex = comp.features.extrudeFeatures
    op = (adsk.fusion.FeatureOperations.CutFeatureOperation if cut
          else adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    inp = ex.createInput(prof, op)
    if symmetric:
        inp.isSymmetricExtent = True
        inp.setDistanceExtent(False,
                              adsk.core.ValueInput.createByReal(depth_mm * MM * 0.5))
    else:
        inp.setDistanceExtent(False, adsk.core.ValueInput.createByReal(depth_mm * MM))
    res = ex.add(inp)
    if cut:
        return None
    body = res.bodies.item(0)
    body.name = name
    return body


