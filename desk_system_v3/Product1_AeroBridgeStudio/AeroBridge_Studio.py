def _move(comp, bodies, dx=0.0, dy=0.0, dz=0.0):
    if not bodies or (abs(dx) + abs(dy) + abs(dz)) < 1e-9:
        return
    coll = adsk.core.ObjectCollection.create()
    for b in bodies:
        coll.add(b)
    m = adsk.core.Matrix3D.create()
    m.translation = adsk.core.Vector3D.create(dx * MM, dy * MM, dz * MM)
    comp.features.moveFeatures.add(
        comp.features.moveFeatures.createInput(coll, m))


